// Writes docs/PRONUNCIATION_REPORT.md from student-app/lessons/pronunciation.js and the A&P lesson data.
// Usage: node tools/pronunciation-report.js          (writes the report)
//        node tools/pronunciation-report.js --check  (exits 1 if the committed report is out of date)
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, ".."), LES = path.join(ROOT, "student-app", "lessons");
global.window = global; window.MuscleSets = {};
require(path.join(LES, "pronunciation.js"));
for (const f of ["muscle-core.js", "muscles.js", "trunk.js", "upper.js", "forearm.js"]) require(path.join(LES, "ap-muscles", f));
const P = window.Pronunciations;
const LESSONS = { head: "Head and neck", trunk: "Trunk", upper: "Shoulder and arm", forearm: "Forearm" };

const rows = [], missing = [];
for (const [key, label] of Object.entries(LESSONS)) {
  for (const m of Object.values(window.MuscleSets[key].MUSCLES)) {
    const r = P.forTerm(m.name);
    if (r.ok) rows.push({ lesson: label, name: m.name, r });
    else missing.push({ lesson: label, name: m.name, words: r.missing });
  }
}
const esc = s => s.replace(/\|/g, "\\|");
let md = "# Pronunciation report (A&P muscle lessons)\n\n";
md += "Generated by `node tools/pronunciation-report.js` from `student-app/lessons/pronunciation.js`. Do not edit by hand.\n\n";
md += `Dictionary: Merriam-Webster (Medical Dictionary where it has an entry, otherwise the general dictionary), read ${P.CHECKED}. ` +
  "Each notation was read from the live entry twice, with two differently worded requests, and both reads agreed character for character.\n\n";
md += `**${rows.length} of ${rows.length + missing.length} lesson muscle names show a pronunciation. ${missing.length} show none.**\n\n`;
md += "Rules: the first pronunciation listed is used; sounds marked optional in parentheses are left out of the simple spelling; " +
  "only the main stressed syllable of each word is in capitals; everyday English words (" + P.EVERYDAY.join(", ") + ") are shown as written and not looked up; " +
  "a name with any unverified word shows no pronunciation at all.\n\n";
md += "Key: " + P.KEY + "\n\n";
md += "## Not shown (no full dictionary pronunciation found)\n\n| Lesson | Name | Word | Why |\n|---|---|---|---|\n";
for (const x of missing) for (const w of x.words) md += `| ${x.lesson} | ${x.name} | ${w} | ${esc(P.NOT_VERIFIED[w] || "Not in the verified list.")} |\n`;
md += "\n## Shown\n\n| Lesson | Name | Say it | Merriam-Webster notation (entry) | Source |\n|---|---|---|---|---|\n";
for (const x of rows) {
  const notes = x.r.sources.map(s => `\\${esc(s.notation)}\\ (${esc(s.entry)})`).join("; ");
  const links = x.r.sources.map(s => `[${s.dict.includes("Medical") ? "Medical" : "General"}](${s.url})`).join(", ");
  md += `| ${x.lesson} | ${x.name} | ${x.r.text}${x.r.singular.length ? " (MW gives the singular)" : ""} | ${notes} | ${links} |\n`;
}
md += "\n## Notes\n\n";
md += "- Merriam-Webster lists two accepted pronunciations for some words, and different entries put a different one first. " +
  "The app follows each muscle's own entry, so teres is TERR-eez in teres major and teres minor but TEER-eez in pronator teres, and brachii is BRAY-kee-ee in biceps brachii but BRAY-kee-eye in triceps brachii. Both forms are correct.\n";
md += "- Intercostals: Merriam-Webster gives only the singular, intercostal, so the app shows that with a note instead of adding a sound.\n";
md += "- No dictionary audio is stored in the app. Each source line links to the Merriam-Webster entry, which has its own audio when online.\n";

const out = path.join(ROOT, "docs", "PRONUNCIATION_REPORT.md");
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
  if (cur !== md) { console.error("docs/PRONUNCIATION_REPORT.md is out of date: run node tools/pronunciation-report.js"); process.exit(1); }
  console.log("Pronunciation report is up to date (" + rows.length + " shown, " + missing.length + " not shown).");
} else { fs.writeFileSync(out, md); console.log("Wrote " + path.relative(ROOT, out) + ": " + rows.length + " shown, " + missing.length + " not shown."); }
